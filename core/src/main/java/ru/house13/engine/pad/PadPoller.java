package ru.house13.engine.pad;

/**
 * Платформенный источник геймпадного ввода. Реализации живут в
 * платформенных модулях и опрашиваются каждый кадр на GL-потоке
 * ДО логических тиков (см. House13Game.render): события сразу
 * уходят в InputQueue и выравниваются с шагом 10 Гц.
 *
 * <p>Фундамент (этап 5e): единственная реализация — GLFW на десктопе
 * ({@code GlfwPadPoller}, lwjgl3-модуль): SDL-нормализация геймпадов
 * встроена в GLFW, внешние зависимости не нужны. Этап 6 (Android)
 * добавит мост на InputDevice/MotionEvent с тем же контрактом.
 *
 * <p>Почему poll, а не события:(GLFW даёт мгновенный срез состояния;
 * диф с прошлым кадром даёт press/release; 60 Гц сэмплирования
 * против минимального тапа ~50 мс — потери нет, а код моста —
 * десяток строк без колбэков и потоков).
 */
public interface PadPoller {

    /**
     * Опрос и маршрутизация событий в router (каждый кадр, GL-поток).
     * Реализация обязана переживать отсутствие геймпада и горячее
     * подключение/отключение (router.padConnected/padDisconnected).
     */
    void poll(PadRouter router);
}
